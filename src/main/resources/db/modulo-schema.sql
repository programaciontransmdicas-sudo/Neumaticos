CREATE SCHEMA IF NOT EXISTS neumaticos;
CREATE TABLE IF NOT EXISTS neumaticos.unidades (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 placa VARCHAR(10) NOT NULL UNIQUE, marca VARCHAR(100) NOT NULL,
 operacion VARCHAR(150) NOT NULL, ruta VARCHAR(200) NOT NULL
);
ALTER TABLE neumaticos.unidades ADD COLUMN IF NOT EXISTS semirremolque TEXT NOT NULL DEFAULT '';
ALTER TABLE neumaticos.unidades ADD COLUMN IF NOT EXISTS modelo TEXT NOT NULL DEFAULT '';
ALTER TABLE neumaticos.unidades ADD COLUMN IF NOT EXISTS tipo TEXT NOT NULL DEFAULT '';
ALTER TABLE neumaticos.unidades ADD COLUMN IF NOT EXISTS requiere_revision BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS neumaticos.catalogo_neumaticos (
 codigo TEXT PRIMARY KEY, marca TEXT NOT NULL, diseno TEXT NOT NULL,
 medida TEXT NOT NULL, reencauche1 TEXT NOT NULL, reencauche2 TEXT NOT NULL, requiere_revision BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS neumaticos.importaciones_modulo (
 clave VARCHAR(100) PRIMARY KEY, creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS neumaticos.documentos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 token VARCHAR(100) NOT NULL UNIQUE, version BIGINT NOT NULL DEFAULT 0,
 tipo VARCHAR(20) NOT NULL, estado VARCHAR(20) NOT NULL,
 placa TEXT NOT NULL DEFAULT '', operador TEXT NOT NULL DEFAULT '', kilometraje BIGINT,
 fecha DATE, ot TEXT NOT NULL DEFAULT '', inicio TIME, fin TIME,
 marca_unidad TEXT NOT NULL DEFAULT '', operacion TEXT NOT NULL DEFAULT '',
 ruta TEXT NOT NULL DEFAULT '', semirremolque TEXT NOT NULL DEFAULT '',
 rotaciones BOOLEAN NOT NULL DEFAULT FALSE, observaciones TEXT NOT NULL DEFAULT '',
 responsable1 TEXT NOT NULL DEFAULT '', responsable2 TEXT NOT NULL DEFAULT '',
 responsable3 TEXT NOT NULL DEFAULT '', responsable4 TEXT NOT NULL DEFAULT '',
 creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (tipo IN ('INSPECCION','CAMBIO','REQUERIMIENTO')),
 CHECK (estado IN ('BORRADOR','GENERADO')),
 CHECK (kilometraje IS NULL OR kilometraje >= 0)
);
CREATE INDEX IF NOT EXISTS documentos_busqueda ON neumaticos.documentos(placa,fecha);
CREATE TABLE IF NOT EXISTS neumaticos.documento_filas (
 documento_id BIGINT NOT NULL REFERENCES neumaticos.documentos(id) ON DELETE CASCADE,
 seccion VARCHAR(10) NOT NULL, indice INTEGER NOT NULL, posicion INTEGER,
 codigo TEXT NOT NULL DEFAULT '', marca TEXT NOT NULL DEFAULT '', diseno TEXT NOT NULL DEFAULT '', medida TEXT NOT NULL DEFAULT '',
 rn TEXT NOT NULL DEFAULT '', r1 NUMERIC, r2 NUMERIC, presion NUMERIC,
 aro TEXT NOT NULL DEFAULT '', condicion TEXT NOT NULL DEFAULT '', sin_tapa VARCHAR(2) NOT NULL DEFAULT '',
 disposicion TEXT NOT NULL DEFAULT '', codigo_nuevo TEXT NOT NULL DEFAULT '',
 marca_nueva TEXT NOT NULL DEFAULT '', diseno_nuevo TEXT NOT NULL DEFAULT '', medida_nueva TEXT NOT NULL DEFAULT '',
 n1 NUMERIC, n2 NUMERIC, cantidad INTEGER, conformidad TEXT NOT NULL DEFAULT '',
 PRIMARY KEY (documento_id,seccion,indice),
 CHECK (seccion IN ('PRINCIPAL','ROTACION'))
);

ALTER TABLE neumaticos.unidades ADD COLUMN IF NOT EXISTS revision BIGINT NOT NULL DEFAULT 0;
ALTER TABLE neumaticos.catalogo_neumaticos ADD COLUMN IF NOT EXISTS revision BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS neumaticos.disposiciones (clave VARCHAR(250) PRIMARY KEY, nombre VARCHAR(250) NOT NULL);
CREATE TABLE IF NOT EXISTS neumaticos.salidas_almacen (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 origen VARCHAR(20) NOT NULL, referencia VARCHAR(150) NOT NULL UNIQUE,
 fecha DATE NOT NULL, codigo VARCHAR(100) NOT NULL, marca VARCHAR(100) NOT NULL, modelo VARCHAR(250) NOT NULL,
 medida VARCHAR(100) NOT NULL DEFAULT '', cantidad INTEGER NOT NULL CHECK(cantidad>0),
 placa VARCHAR(100) NOT NULL DEFAULT '', observaciones TEXT NOT NULL DEFAULT '',
 creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS salidas_fecha ON neumaticos.salidas_almacen(fecha);
CREATE INDEX IF NOT EXISTS salidas_marca_modelo ON neumaticos.salidas_almacen(marca,modelo);

CREATE TABLE IF NOT EXISTS neumaticos.operadores (
 busqueda VARCHAR(250) PRIMARY KEY, nombre VARCHAR(250) NOT NULL
);
